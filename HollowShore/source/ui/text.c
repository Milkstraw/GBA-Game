/* -----------------------------------------------------------------------
 * Internal: expand one 1bpp glyph to 4bpp and write into charblock 3 VRAM.
 *
 * GBA 4bpp tile layout (32 bytes per 8x8 tile):
 *   4 bytes per row (32 bytes total).
 *   Each byte holds two pixels: bits[3:0] = left pixel, bits[7:4] = right pixel.
 *   We write as u16 pairs: (row * 2) u16 words per row.
 *
 * tile_index: which tile slot in charblock 3 (0-based).
 * -------------------------------------------------------------------- */
static void upload_glyph(u16 tile_index, const u8 rows[8])
{
    /* Charblock 3 base + tile offset (each tile = 16 u16 words = 32 bytes) */
    vu16 *dst = CHARBLOCK_3_BASE + (u32)(tile_index * 16u);
    u8 row;

    for (row = 0; row < 8u; row++) {
        u8 bits = rows[row];
        u8 col;
        /* 8 pixels -> 4 u16 words (2 pixels per u16) */
        for (col = 0; col < 4u; col++) {
            /* Pixels counted left to right, MSB first */
            u8 p0 = (u8)((bits >> (u8)(7u - col * 2u))     & 1u);
            u8 p1 = (u8)((bits >> (u8)(7u - col * 2u - 1u)) & 1u);
            /* 4bpp: each nibble is a palette index */
            u16 word = (u16)(p0 | ((u16)p1 << 4u));
            dst[(u16)(row * 4u + col)] = word;
        }
    }
}

/* -----------------------------------------------------------------------
 * Public API
 * -------------------------------------------------------------------- */

void text_init(void)
{
    u8 g;

    /* BG3CNT: charblock 3, screenblock 30, 256x256, 4bpp */
    REG_BG3CNT = BG3CNT_TEXT_LAYER;

    /* BG palette bank 1 (entries 16–17): 0 = transparent, 1 = white.
     * Bank 0 is reserved for BG0 world tiles; using bank 1 avoids conflict. */
    BG_PAL_BASE[16] = 0x0000u;
    BG_PAL_BASE[17] = RGB15(31, 31, 31);

    /* Upload all 96 glyphs to charblock 3 (tile indices 0-95) */
    for (g = 0u; g < 96u; g++) {
        upload_glyph((u16)g, font_1bpp[g]);
    }

    text_clear();
}

void text_draw(u8 x, u8 y, const char *str)
{
    u8 cx = x;
    u8 cy = y;

    while (*str != '\0') {
        char c = *str;
        str++;

        if (c == '\n') {
            cy++;
            cx = x;
            continue;
        }

        if (c >= 32 && c <= 127 && cx < 30u && cy < 20u) {
            u16 tile  = (u16)((u8)c - 32u);
            u16 index = (u16)(cy * 32u + cx);
            /* bits 15-12 = palette bank 1 */
            SCREENBLOCK_30[index] = (u16)(tile | (1u << 12));
        }
        cx++;
        if (cx >= 30u) {
            cx = 0u;
            cy++;
        }
    }
}

void text_draw_int(u8 x, u8 y, s32 val)
{
    /* Buffer large enough for INT32_MIN ("-2147483648") + NUL */
    char buf[12];
    u8   pos = 11u;
    u8   neg = 0u;
    u32  uval;

    buf[pos] = '\0';

    if (val < 0) {
        neg = 1u;
        /* Safe conversion avoiding UB on INT32_MIN */
        uval = (u32)(-(val + 1)) + 1u;
    } else {
        uval = (u32)val;
    }

    /* Handle zero */
    if (uval == 0u) {
        pos--;
        buf[pos] = '0';
    } else {
        while (uval > 0u) {
            pos--;
            buf[pos] = (char)('0' + (uval % 10u));
            uval /= 10u;
        }
    }

    if (neg) {
        pos--;
        buf[pos] = '-';
    }

    text_draw(x, y, &buf[pos]);
}

void text_clear(void)
{
    u16 i;
    /* Tile index 0 = space (ASCII 32). Fill all 32x32 = 1024 map entries. */
    for (i = 0u; i < 1024u; i++) {
        SCREENBLOCK_30[i] = 0u;
    }
}
