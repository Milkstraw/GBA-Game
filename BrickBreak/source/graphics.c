void gba_clearScreen(u16 color) {
    u32 c32 = (u32)color | ((u32)color << 16);
    volatile u32 *dst = (volatile u32*)VRAM;
    int i;
    for (i = 0; i < (SCREEN_WIDTH * SCREEN_HEIGHT / 2); i++)
        dst[i] = c32;
}

void gba_setPixel(int x, int y, u16 color) {
    if ((unsigned)x < (unsigned)SCREEN_WIDTH &&
        (unsigned)y < (unsigned)SCREEN_HEIGHT)
        VRAM[y * SCREEN_WIDTH + x] = color;
}

void gba_fillRect(int x, int y, int w, int h, u16 color) {
    int x2 = x + w;
    int y2 = y + h;
    int row, col;
    if (x  < 0)            x  = 0;
    if (y  < 0)            y  = 0;
    if (x2 > SCREEN_WIDTH) x2 = SCREEN_WIDTH;
    if (y2 > SCREEN_HEIGHT)y2 = SCREEN_HEIGHT;
    for (row = y; row < y2; row++) {
        volatile u16 *p = VRAM + row * SCREEN_WIDTH + x;
        for (col = x; col < x2; col++)
            *p++ = color;
    }
}

void gba_drawRect(int x, int y, int w, int h, u16 color) {
    gba_drawHLine(x,         y,         w, color);
    gba_drawHLine(x,         y + h - 1, w, color);
    gba_fillRect (x,         y + 1, 1, h - 2, color);
    gba_fillRect (x + w - 1, y + 1, 1, h - 2, color);
}

void gba_drawHLine(int x, int y, int w, u16 color) {
    gba_fillRect(x, y, w, 1, color);
}

int gba_drawChar(int x, int y, char c, u16 fg, u16 bg) {
    int col, row;
    if ((unsigned char)c < FONT_FIRST ||
        (unsigned char)c > (FONT_FIRST + 95))
        c = ' ';
    {
        const u8 *glyph = font5x7[(unsigned char)c - FONT_FIRST];
        for (col = 0; col < FONT_W; col++) {
            u8 bits = glyph[col];
            for (row = 0; row < FONT_H; row++) {
                u16 px = (bits & (1 << row)) ? fg : bg;
                gba_setPixel(x + col, y + row, px);
            }
        }
    }
    return FONT_W + FONT_GAP;
}

void gba_drawString(int x, int y, const char *str, u16 fg, u16 bg) {
    while (*str)
        x += gba_drawChar(x, y, *str++, fg, bg);
}

void gba_drawNumber(int x, int y, int num, u16 fg, u16 bg) {
    char buf[12];
    int  i = 0, j;
    char tmp[10];
    if (num < 0) { buf[i++] = '-'; num = -num; }
    if (num == 0) {
        buf[i++] = '0';
    } else {
        j = 0;
        while (num > 0) { tmp[j++] = '0' + (num % 10); num /= 10; }
        while (j > 0)    buf[i++] = tmp[--j];
    }
    buf[i] = '\0';
    gba_drawString(x, y, buf, fg, bg);
}

int gba_stringWidth(const char *str) {
    int w = 0;
    while (*str++) w += FONT_W + FONT_GAP;
    return w > 0 ? w - FONT_GAP : 0;
}
